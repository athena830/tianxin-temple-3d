  return `兩隻同色同字的${character}，${selfOrOuter}。${pieceText}。${colorNotice}。當卦象中出現兩隻相同棋子且為同色配置時，形成「消耗格」。此格局象徵能量集中在某一種特質上，若未能平衡運用，容易形成內在消耗的狀態。這種消耗往往不是外在造成，而是來自於個人的性格傾向或內在壓力，使事情推動時感到特別費力。提醒當事人適時調整節奏，避免過度用力或陷入慣性的思考模式。當能量回到平衡的位置時，原本的消耗反而能轉化為穩定的力量。`
