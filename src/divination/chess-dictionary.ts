export function getPieceAspectText(piece: ChessPiece, pos: ChessPos): string {
  const dict = PIECE_ASPECT_INTERPRETATIONS[piece.name]
  if (dict && dict[pos]) return dict[pos]
  return `${piece.color === 'red' ? '紅方' : '黑方'}【${piece.name}】落於${pos}，代表此方位具備相應之生剋運勢。`
}
